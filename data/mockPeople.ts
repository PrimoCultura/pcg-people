export function getPersonById(id: string): Person | undefined {
  return mockPeople.find((person) => person.id === id);
}

export function getManager(person: Person): Person | undefined {
  if (!person.managerId) return undefined;
  return getPersonById(person.managerId);
}

export function getDirectReports(personId: string): Person[] {
  return mockPeople
    .filter((person) => person.managerId === personId)
    .sort((a, b) =>
      `${a.lastName} ${a.firstName}`.localeCompare(
        `${b.lastName} ${b.firstName}`,
        "it",
      ),
    );
}
